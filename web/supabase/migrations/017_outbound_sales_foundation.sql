-- ============================================================
-- 1. STOCK MOVEMENT METADATA
-- ============================================================

alter table public.stock_movements
  add column if not exists transaction_type text;

alter table public.stock_movements
  add column if not exists sales_channel text;


-- Existing outbound history is preserved.
-- Old outbound records without a transaction type are classified
-- as Other rather than changing or deleting their history.

update public.stock_movements
set transaction_type = 'Other'
where movement_type = 'outbound'
  and transaction_type is null;


-- ============================================================
-- 2. SALES TRANSACTIONS
-- ============================================================

create table if not exists public.sales_transactions (
  id uuid primary key default gen_random_uuid(),

  sales_no bigint generated by default as identity unique,

  stock_movement_id uuid not null
    references public.stock_movements(id)
    on delete restrict,

  variant_id uuid not null
    references public.product_variants(id)
    on delete restrict,

  quantity integer not null
    check (quantity > 0),

  hpp_snapshot numeric(14,2) not null
    check (hpp_snapshot >= 0),

  selling_price_snapshot numeric(14,2) not null
    check (selling_price_snapshot >= 0),

  gross_sales numeric(14,2) not null
    check (gross_sales >= 0),

  discount numeric(14,2) not null default 0
    check (discount >= 0),

  net_sales numeric(14,2) not null
    check (net_sales >= 0),

  sales_channel text not null,

  reference_no text not null,

  transaction_date timestamptz not null default now(),

  notes text,

  created_by uuid
    references auth.users(id)
    on delete set null,

  created_at timestamptz not null default now(),

  constraint sales_transactions_movement_unique
    unique (stock_movement_id),

  constraint sales_transactions_net_not_over_gross
    check (net_sales <= gross_sales),

  constraint sales_transactions_channel_check
    check (
      sales_channel in (
        'TikTok Shop',
        'Shopee',
        'Tokopedia',
        'Lazada',
        'Website',
        'WhatsApp',
        'Offline Store',
        'Bazaar/Event',
        'Wholesale/Reseller',
        'Other'
      )
    )
);


-- ============================================================
-- 3. INDEXES
-- ============================================================

create index if not exists idx_sales_transactions_variant
  on public.sales_transactions(variant_id);

create index if not exists idx_sales_transactions_date
  on public.sales_transactions(transaction_date);

create index if not exists idx_sales_transactions_channel
  on public.sales_transactions(sales_channel);

create index if not exists idx_sales_transactions_reference
  on public.sales_transactions(reference_no);


-- ============================================================
-- 4. RLS / TABLE SECURITY
--
-- Sales data is NOT directly writable/readable from the browser
-- at this stage.
--
-- Future role-specific read access will be added together with
-- the final role architecture.
-- ============================================================

alter table public.sales_transactions
  enable row level security;

revoke all on table public.sales_transactions
  from anon, authenticated;

grant all on table public.sales_transactions
  to service_role;


-- ============================================================
-- 5. NEW ATOMIC OUTBOUND TRANSACTION RPC
-- ============================================================

create or replace function public.post_outbound_transaction(
  p_variant_id uuid,
  p_from_location_id uuid,
  p_quantity integer,
  p_transaction_type text,
  p_reference_no text,
  p_sales_channel text default null,
  p_discount numeric default 0,
  p_notes text default null
)
returns table (
  new_movement_no bigint,
  source_qty_after integer,

  transaction_type text,
  sales_channel text,

  hpp_snapshot numeric(14,2),
  selling_price_snapshot numeric(14,2),

  gross_sales numeric(14,2),
  discount numeric(14,2),
  net_sales numeric(14,2),

  sales_transaction_id uuid,
  sales_no bigint,

  transaction_date timestamptz
)

language plpgsql
security definer
set search_path = public, pg_temp

as $$
declare
  v_source_qty integer;
  v_source_after integer;

  v_area_code text;

  v_product_id uuid;

  v_hpp numeric(14,2);
  v_selling_price numeric(14,2);

  v_gross_sales numeric(14,2);
  v_discount numeric(14,2);
  v_net_sales numeric(14,2);

  v_movement_id uuid;
  v_movement_no bigint;

  v_sales_transaction_id uuid;
  v_sales_no bigint;

  v_transaction_date timestamptz := now();

begin

  -- ==========================================================
  -- AUTHENTICATION
  -- ==========================================================

  if auth.uid() is null then
    raise exception 'User belum login';
  end if;


  -- ==========================================================
  -- ROLE AUTHORIZATION
  -- Same stock-changing roles used by existing WMS.
  -- ==========================================================

  if not exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and is_active = true
      and role in (
        'owner',
        'admin',
        'warehouse_manager',
        'warehouse_staff'
      )
  ) then
    raise exception
      'User tidak memiliki akses untuk melakukan outbound';
  end if;


  -- ==========================================================
  -- BASIC VALIDATION
  -- ==========================================================

  if p_quantity is null or p_quantity <= 0 then
    raise exception
      'Quantity harus lebih dari 0';
  end if;


  if coalesce(trim(p_reference_no), '') = '' then
    raise exception
      'Reference wajib diisi';
  end if;


  if coalesce(trim(p_transaction_type), '') not in (
    'Sale',
    'Sample',
    'Giveaway',
    'Internal Use',
    'Other'
  ) then
    raise exception
      'Transaction Type tidak valid';
  end if;


  v_discount := coalesce(p_discount, 0);


  if v_discount < 0 then
    raise exception
      'Discount tidak boleh negatif';
  end if;


  -- ==========================================================
  -- SALES VALIDATION
  -- ==========================================================

  if trim(p_transaction_type) = 'Sale' then

    if coalesce(trim(p_sales_channel), '') not in (
      'TikTok Shop',
      'Shopee',
      'Tokopedia',
      'Lazada',
      'Website',
      'WhatsApp',
      'Offline Store',
      'Bazaar/Event',
      'Wholesale/Reseller',
      'Other'
    ) then
      raise exception
        'Sales Channel wajib dipilih untuk transaksi Sale';
    end if;

  else

    if coalesce(trim(p_sales_channel), '') <> '' then
      raise exception
        'Sales Channel hanya boleh diisi untuk transaksi Sale';
    end if;

    if v_discount <> 0 then
      raise exception
        'Discount hanya boleh diisi untuk transaksi Sale';
    end if;

  end if;


  -- ==========================================================
  -- VALIDATE SKU + READ CURRENT HPP / SELLING PRICE
  --
  -- Snapshot is taken INSIDE the database transaction.
  -- ==========================================================

  select
    pv.product_id,
    pv.hpp,
    pv.selling_price
  into
    v_product_id,
    v_hpp,
    v_selling_price
  from public.product_variants pv
  where pv.id = p_variant_id;


  if not found then
    raise exception
      'Variant / SKU tidak ditemukan';
  end if;


  -- ==========================================================
  -- SALE MUST HAVE VALID HPP + SELLING PRICE
  -- ==========================================================

  if trim(p_transaction_type) = 'Sale' then

    if v_hpp is null then
      raise exception
        'HPP SKU belum diisi';
    end if;

    if v_selling_price is null or v_selling_price <= 0 then
      raise exception
        'Harga jual SKU belum diisi';
    end if;

  end if;


  -- ==========================================================
  -- VALIDATE SOURCE LOCATION
  -- ==========================================================

  select
    upper(sa.code)
  into
    v_area_code
  from public.locations l
  join public.stock_areas sa
    on sa.id = l.area_id
  where
    l.id = p_from_location_id
    and l.is_active = true;


  if v_area_code is null then
    raise exception
      'Lokasi asal tidak ditemukan / tidak aktif';
  end if;


  if v_area_code <> 'NORMAL' then
    raise exception
      'Outbound hanya diperbolehkan dari area NORMAL';
  end if;


  -- ==========================================================
  -- LOCK SOURCE INVENTORY
  -- ==========================================================

  select
    qty_on_hand
  into
    v_source_qty
  from public.inventory
  where
    variant_id = p_variant_id
    and location_id = p_from_location_id
  for update;


  if v_source_qty is null then
    raise exception
      'SKU tidak memiliki stok di lokasi asal';
  end if;


  if v_source_qty < p_quantity then
    raise exception
      'Stok tidak cukup. Tersedia: %, diminta: %',
      v_source_qty,
      p_quantity;
  end if;


  -- ==========================================================
  -- DEDUCT INVENTORY
  -- ==========================================================

  update public.inventory
  set
    qty_on_hand = qty_on_hand - p_quantity,
    updated_at = now()
  where
    variant_id = p_variant_id
    and location_id = p_from_location_id
  returning qty_on_hand
  into v_source_after;


  -- ==========================================================
  -- CALCULATE SALES SNAPSHOT
  -- ==========================================================

  if trim(p_transaction_type) = 'Sale' then

    v_gross_sales :=
      round(
        v_selling_price * p_quantity,
        2
      );

    if v_discount > v_gross_sales then
      raise exception
        'Discount tidak boleh melebihi nilai penjualan';
    end if;

    v_net_sales :=
      round(
        v_gross_sales - v_discount,
        2
      );

  else

    v_hpp := null;
    v_selling_price := null;
    v_gross_sales := null;
    v_discount := null;
    v_net_sales := null;

  end if;


  -- ==========================================================
  -- CREATE STOCK MOVEMENT
  -- ==========================================================

  insert into public.stock_movements (
    movement_type,
    variant_id,
    from_location_id,
    to_location_id,
    quantity,
    reason,
    reference_no,
    notes,
    created_by,
    created_at,
    transaction_type,
    sales_channel
  )
  values (
    'outbound',
    p_variant_id,
    p_from_location_id,
    null,
    p_quantity,

    case trim(p_transaction_type)
      when 'Sale'
        then 'Outbound - Sale'
      when 'Sample'
        then 'Outbound - Sample'
      when 'Giveaway'
        then 'Outbound - Giveaway'
      when 'Internal Use'
        then 'Outbound - Internal Use'
      else
        'Outbound - Other'
    end,

    trim(p_reference_no),
    nullif(trim(p_notes), ''),
    auth.uid(),
    v_transaction_date,

    trim(p_transaction_type),

    case
      when trim(p_transaction_type) = 'Sale'
        then trim(p_sales_channel)
      else null
    end
  )
  returning
    id,
    movement_no
  into
    v_movement_id,
    v_movement_no;


  -- ==========================================================
  -- CREATE SALES TRANSACTION ONLY FOR SALE
  -- ==========================================================

  if trim(p_transaction_type) = 'Sale' then

    insert into public.sales_transactions (
      stock_movement_id,
      variant_id,
      quantity,
      hpp_snapshot,
      selling_price_snapshot,
      gross_sales,
      discount,
      net_sales,
      sales_channel,
      reference_no,
      transaction_date,
      notes,
      created_by,
      created_at
    )
    values (
      v_movement_id,
      p_variant_id,
      p_quantity,
      v_hpp,
      v_selling_price,
      v_gross_sales,
      v_discount,
      v_net_sales,
      trim(p_sales_channel),
      trim(p_reference_no),
      v_transaction_date,
      nullif(trim(p_notes), ''),
      auth.uid(),
      v_transaction_date
    )
    returning
      id,
      sales_no
    into
      v_sales_transaction_id,
      v_sales_no;


    -- ========================================================
    -- UPDATE PRODUCT / VARIANT SALE LIFECYCLE
    -- ========================================================

    update public.product_variants
    set
      first_sale_date =
        coalesce(first_sale_date, v_transaction_date),
      last_sale_date =
        v_transaction_date
    where id = p_variant_id;


    update public.products
    set
      first_sale_date =
        coalesce(first_sale_date, v_transaction_date),
      last_sale_date =
        v_transaction_date
    where id = v_product_id;

  end if;


  -- ==========================================================
  -- RETURN RESULT
  -- ==========================================================

  return query
  select
    v_movement_no,
    v_source_after,

    trim(p_transaction_type),

    case
      when trim(p_transaction_type) = 'Sale'
        then trim(p_sales_channel)
      else null
    end,

    v_hpp,
    v_selling_price,

    v_gross_sales,
    v_discount,
    v_net_sales,

    v_sales_transaction_id,
    v_sales_no,

    v_transaction_date;

end;
$$;


-- ============================================================
-- 6. FUNCTION SECURITY
-- ============================================================

revoke all on function public.post_outbound_transaction(
  uuid,
  uuid,
  integer,
  text,
  text,
  text,
  numeric,
  text
) from public;


grant execute on function public.post_outbound_transaction(
  uuid,
  uuid,
  integer,
  text,
  text,
  text,
  numeric,
  text
) to authenticated;


